#!/usr/bin/env node
/**
 * Generate per-route page.tsx wrappers that load the locale-specific
 * MDX file at request time.
 *
 * Why a per-route wrapper instead of a catch-all [...slug]/page.tsx:
 *   - Static routing yields a deterministic route table at build time
 *     (each path shows up in the build manifest).
 *   - Per-route page.tsx lets each page declare its own metadata and
 *     locale-specific MDX imports without runtime branching by string.
 *
 * Why per-locale MDX file (en.mdx/zh.mdx/de.mdx) instead of a single
 * file with runtime branching:
 *   - MDX compiles at build time. Per-locale files compile cleanly
 *     into per-locale RSC payloads.
 *   - The wrapper picks the right module via static import + locale
 *     param. No runtime fs access (Worker can't fs.readFile).
 *
 * Note: docs render dynamically (force-dynamic in layout.tsx) so the
 * parent locale layout's per-request CSP nonce stays correct; the
 * static import + locale branching here is unaffected.
 */

import { readdirSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, '..', '..');
const DOCS_ROOT = resolve(REPO_ROOT, 'src/app/[locale]/docs');

const WRAPPER_TEMPLATE = (relPath) => `import type { Metadata } from 'next';
import { setRequestLocale } from 'next-intl/server';
import { notFound } from 'next/navigation';
import EnContent, { frontmatter as enFrontmatter } from './en.mdx';
import ZhContent, { frontmatter as zhFrontmatter } from './zh.mdx';
import DeContent, { frontmatter as deFrontmatter } from './de.mdx';

/**
 * Per-route wrapper — auto-generated by
 * scripts/docs-migration/generate-page-wrappers.mjs.
 *
 * Picks the locale-specific MDX at render time. If a translation is
 * missing the EN fallback is served (zh.mdx / de.mdx for API pages
 * are EN copies until translations land — see migrate.mjs §applyFallback).
 *
 * Path: ${relPath}
 */
type Props = {
  params: Promise<{ locale: string }>;
};

const FRONTMATTER: Record<string, { title?: string; description?: string }> = {
  en: enFrontmatter ?? {},
  zh: zhFrontmatter ?? {},
  de: deFrontmatter ?? {},
};

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { locale } = await params;
  const fm = FRONTMATTER[locale] ?? FRONTMATTER.en;
  return {
    title: fm.title ? \`\${fm.title} · Aster Cloud Docs\` : 'Aster Cloud Docs',
    description: fm.description,
  };
}

export default async function Page({ params }: Props) {
  const { locale } = await params;
  setRequestLocale(locale);
  if (locale === 'zh') return <ZhContent />;
  if (locale === 'de') return <DeContent />;
  if (locale === 'en') return <EnContent />;
  notFound();
}
`;

function walk(dir, files = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const s = statSync(full);
    if (s.isDirectory()) walk(full, files);
    else if (name === 'en.mdx') files.push(dirname(full));
  }
  return files;
}

const routeDirs = walk(DOCS_ROOT);
let count = 0;
for (const routeDir of routeDirs) {
  const wrapperPath = join(routeDir, 'page.tsx');
  const rel = routeDir.replace(REPO_ROOT + '/', '');
  writeFileSync(wrapperPath, WRAPPER_TEMPLATE(rel));
  count += 1;
}
console.log(`[wrappers] generated ${count} page.tsx files`);
